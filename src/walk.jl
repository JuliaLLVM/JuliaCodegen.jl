# The backend-agnostic front half: walking typed `IRCode` statement by statement.
#
# A backend provides a function context `<: AbstractFnCtx` with the fields `ir`,
# `ssavals`, `args` and `cur_block`, and methods for the hooks below; the walker owns the
# traversal order, operand resolution, folding of constant branches, the generic
# expression heads and the handling of the statements' result types.
#
# Hooks (all take the context first):
#
#   begin_block!(fc, bi)                     start emitting IR block `bi`
#   block_reachable(fc, bi)                  false if no branch to block `bi` was emitted
#   emit_goto!(fc, target)                   branch (records the edge for phi inputs)
#   emit_cond_goto!(fc, cond, next, dest)    two-way branch on a run-time Bool
#   emit_return!(fc, v)                      return `v`
#   emit_unreachable_term!(fc)               `unreachable` as a terminator
#   emit_phi!(fc, idx, node, typ)            the value of a PhiNode
#   convert_value(fc, v, typ)                change of representation (PiNode, results)
#   const_value(fc, x)                       a compile-time constant
#   nonconst_global(fc, ref)                 read of a non-constant global binding
#   emit_call!(fc, f, ex, typ)               `:call` (intrinsics, builtins, dynamic)
#   emit_invoke!(fc, ex, typ)                `:invoke`
#   emit_new!(fc, T, args, typ)              `:new`
#   emit_new_dynamic!(fc, T, args, typ)      `:new` of a type known only at run time
#   emit_expr_head!(fc, idx, ex, typ)        any other expression head
#   emit_special_stmt!(fc, idx, stmt, typ)   EnterNode/UpsilonNode/PhiCNode; returns
#                                            whether the statement terminated the block
#   noreturn!(fc, res)                       after a statement of type Union{}
#   method_instance(fc)                      for `:static_parameter`
#   codegen_world(fc)                        the world the code is compiled for
#
# Values have a `typ` field; `isconstant(v)`/`constant_value(v)` give compile-time
# values, and `isbottom(v)` says that a value doesn't exist (dead code).

"""
    JuliaCodegen.AbstractFnCtx

The context of a function being generated by a backend, which the IR walker drives (see
`src/walk.jl` for the hooks a backend implements).
"""
abstract type AbstractFnCtx end

const NOOP_HEADS = (:code_coverage_effect, :meta, :inbounds, :loopinfo, :aliasscope,
                    :popaliasscope, :latestworld)

"""
    JuliaCodegen.walk_function!(fc::AbstractFnCtx)

Emit the IR of `fc.ir`, block by block.
"""
function walk_function!(fc::AbstractFnCtx)
    ir = fc.ir
    nb = length(ir.cfg.blocks)
    for (bi, bb) in enumerate(ir.cfg.blocks)
        fc.cur_block = bi
        begin_block!(fc, bi)
        if !block_reachable(fc, bi)
            # no branch to this block was emitted (e.g. it follows a statement found to
            # throw): native code does not emit it either, and its values may not exist
            emit_unreachable_term!(fc)
            continue
        end
        terminated = false
        for idx in bb.stmts
            stmt = ir.stmts.stmt[idx]
            typ = CC.widenconst(ir.stmts.type[idx])
            begin_stmt!(fc, idx)
            terminated = walk_stmt!(fc, idx, stmt, typ)
            terminated && break
        end
        if !terminated
            if bi < nb
                emit_goto!(fc, bi + 1)
            elseif isempty(bb.preds) && bi > 1
                # dead code after the last `return` (e.g. a `:meta` left by `@allocations`)
                emit_unreachable_term!(fc)
            else
                unsupported("fallthrough out of the last block")
            end
        end
    end
    return fc
end

function walk_stmt!(fc::AbstractFnCtx, idx::Int, @nospecialize(stmt), @nospecialize(typ))
    if stmt isa Core.GotoNode
        emit_goto!(fc, stmt.label)
        return true
    elseif stmt isa Core.GotoIfNot
        c = operand(fc, stmt.cond)
        next, dest = fc.cur_block + 1, stmt.dest
        if isconstant(c)
            emit_goto!(fc, constant_value(c) ? next : dest)
        elseif next == dest
            emit_goto!(fc, next)
        else
            emit_cond_goto!(fc, c, next, dest)
        end
        return true
    elseif stmt isa Core.ReturnNode
        if isdefined(stmt, :val)
            emit_return!(fc, operand(fc, stmt.val))
        else
            emit_unreachable_term!(fc)
        end
        return true
    elseif stmt isa Core.PhiNode
        fc.ssavals[idx] = emit_phi!(fc, idx, stmt, typ)
    elseif stmt isa Core.PiNode
        v = operand(fc, stmt.val)
        r = fc.ssavals[idx] = convert_value(fc, v, typ)
        # narrowed to a type it cannot have: the rest of the block is dead
        isbottom(r) && !isbottom(v) && return dead_rest!(fc)
    elseif stmt isa Core.EnterNode || stmt isa Core.UpsilonNode || stmt isa Core.PhiCNode
        return emit_special_stmt!(fc, idx, stmt, typ)
    elseif stmt isa Expr
        res = walk_expr!(fc, idx, stmt, typ)
        if typ === Union{}
            noreturn!(fc, res)
        elseif res !== nothing
            r = fc.ssavals[idx] = res.typ === typ ? res : convert_value(fc, res, typ)
            # the expression was found to throw (e.g. a `new` with a mistyped field)
            isbottom(r) && return dead_rest!(fc)
        end
    elseif stmt === nothing
    else
        fc.ssavals[idx] = convert_value(fc, operand(fc, stmt), typ)
    end
    return false
end

# the code after a statement that never returns is dead: terminate the block
function dead_rest!(fc::AbstractFnCtx)
    emit_unreachable_term!(fc)
    return true
end

function walk_expr!(fc::AbstractFnCtx, idx::Int, ex::Expr, @nospecialize(typ))
    head = ex.head
    if head === :call
        return emit_call!(fc, operand(fc, ex.args[1]), ex, typ)
    elseif head === :invoke
        return emit_invoke!(fc, ex, typ)
    elseif head === :new
        T = operand(fc, ex.args[1])
        args = [operand(fc, a) for a in ex.args[2:end]]
        isconstant(T) || return emit_new_dynamic!(fc, T, args, typ)
        return emit_new!(fc, constant_value(T), args, typ)
    elseif head === :boundscheck
        # `Expr(:boundscheck, false)` marks a check inside `@inbounds`; --check-bounds
        # overrides both (as `bounds_check_enabled` in the C++ code generator)
        cb = Base.JLOptions().check_bounds
        cb == 1 && return const_value(fc, true)
        cb == 2 && return const_value(fc, false)
        return const_value(fc, isempty(ex.args) ? true : ex.args[1] !== false)
    elseif head === :static_parameter
        return const_value(fc, method_instance(fc).sparam_vals[ex.args[1]::Int])
    elseif head in NOOP_HEADS
        return nothing
    end
    return emit_expr_head!(fc, idx, ex, typ)
end

"""
    JuliaCodegen.operand(fc, x)

The value of the operand `x` of a statement.
"""
function operand(fc::AbstractFnCtx, @nospecialize x)
    if x isa Core.SSAValue
        v = fc.ssavals[x.id]
        v === nothing && unsupported("a use of the undefined SSA value %", x.id)
        return v
    elseif x isa Core.Argument
        return fc.args[x.n]
    elseif x isa GlobalRef
        c = const_global(codegen_world(fc), x.mod, x.name)
        c === nothing || return const_value(fc, something(c))
        return nonconst_global(fc, x)
    elseif x isa QuoteNode
        return const_value(fc, x.value)
    elseif x isa Core.BindingPartition
        # lowering refers to constant globals by their binding partition
        if Base.is_defined_const_binding(Base.binding_kind(x))
            return const_value(fc, x.restriction)
        end
        b = ccall(:jl_binding_partition_owner, Any, (Any,), x)::Core.Binding
        return nonconst_global(fc, b.globalref)
    elseif x isa Expr
        unsupported("a nested expression ", x.head)
    end
    return const_value(fc, x)
end

# The value of a constant global in `world` (`nothing` if it is not one there). Bindings
# are looked up in the world the code is compiled for, not the one the code generator
# runs in, which may see different bindings.
function const_global(world::UInt, m::Module, s::Symbol)
    Base.invoke_in_world(world, isconst, m, s) || return nothing
    return Some(Base.invoke_in_world(world, getglobal, m, s))
end

# defaults
codegen_world(fc::AbstractFnCtx) = Base.get_world_counter()
block_reachable(fc::AbstractFnCtx, bi) = true
isbottom(@nospecialize v) = false
begin_stmt!(fc::AbstractFnCtx, idx) = nothing
emit_special_stmt!(fc::AbstractFnCtx, idx, @nospecialize(stmt), @nospecialize(typ)) =
    unsupported(typeof(stmt))
nonconst_global(fc::AbstractFnCtx, ref::GlobalRef) =
    unsupported("a read of the non-constant global ", ref)
emit_call!(fc::AbstractFnCtx, f, ex::Expr, @nospecialize(typ)) =
    unsupported("a call of ", isconstant(f) ? constant_value(f) : f.typ)
emit_invoke!(fc::AbstractFnCtx, ex::Expr, @nospecialize(typ)) =
    unsupported("an invoke of ", ex.args[1])
emit_new!(fc::AbstractFnCtx, @nospecialize(T), args, @nospecialize(typ)) =
    unsupported("`new` of ", T)
emit_new_dynamic!(fc::AbstractFnCtx, T, args, @nospecialize(typ)) =
    unsupported("`new` of a type that is not known at compile time")
emit_expr_head!(fc::AbstractFnCtx, idx, ex::Expr, @nospecialize(typ)) =
    unsupported("the expression head ", ex.head)
